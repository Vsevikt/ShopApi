namespace MyCalculator
{
    public class Calculator
    {
        public static int Sum(int a, int b)
        {
            return a + b;
        }

        public static int Min(int a, int b)
        {
            return a - b;
        }

        public static int Multiply(int a, int b)
        {
            return a * b;
        }

        public static int Devide(int a, int b)
        {
            return a / b;
        }
    }
}
